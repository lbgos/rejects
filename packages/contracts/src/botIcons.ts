export type BotIconGroup = keyof typeof BOT_ICON_GROUPS;
export const BOT_ICON_NAMES = Object.values(BOT_ICON_GROUPS).flat();
export type BotIconName = (typeof BOT_ICON_NAMES)[number];

const NAMES: ReadonlySet<string> = new Set(BOT_ICON_NAMES);
export const isBotIconName = (name: string): name is BotIconName => NAMES.has(name);

export const similarBotIcons = (query: string, limit = 12): ReadonlyArray<BotIconName> => {
  const wanted = query.trim().toLowerCase();
  const words = wanted.split(/[^a-z0-9]+/).filter((word) => word.length > 2);
  return BOT_ICON_NAMES.filter(
    (name) => name.includes(wanted) || words.some((word) => name.includes(word)),
  ).slice(0, limit);
};
